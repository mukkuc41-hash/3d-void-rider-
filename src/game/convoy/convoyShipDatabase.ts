export function getConvoyShipDef(shipId: string): ConvoyPlayableShipDef {
  const resolvedId = SHIP_ID_ALIASES[shipId] || shipId;
  const match = [...SAVIOUR_SHIPS, ...HUNTER_SHIPS].find(s => s.id === resolvedId);
  if (match) return match;
  return resolvedId.startsWith('hunter') ? HUNTER_SHIPS[0] : SAVIOUR_SHIPS[0];
}
